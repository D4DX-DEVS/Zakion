-- The system types shown as cards on the Solutions page (On Grid, Hybrid, Battery Energy Storage ...) and on their own pages (/services/<slug>/).
-- Managed in the admin under Systems. `features` is a JSON list of {icon, title, text}; `details` is optional formatted text (HTML).
CREATE TABLE systems (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  thumb TEXT NOT NULL DEFAULT '',
  badge TEXT NOT NULL DEFAULT '',
  heading TEXT NOT NULL DEFAULT '',
  text TEXT NOT NULL DEFAULT '',
  image TEXT NOT NULL DEFAULT '',
  image2 TEXT NOT NULL DEFAULT '',
  features TEXT NOT NULL DEFAULT '[]',
  details TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'published',
  sort INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX systems_status_sort ON systems (status, sort);

