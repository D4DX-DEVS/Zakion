// Turns the brand colours in public/zk-*.css into overridable CSS variables, so Site settings > Theme colours can recolour the site.
//
//   #0d3d7b            ->  var(--zc-0d3d7b,#0d3d7b)          (the original colour stays as the fallback, so nothing changes until a theme is set)
//   rgba(13,61,123,.3) ->  rgba(var(--zr-0d3d7b,13,61,123),.3)
//
// Only the blue family (the navy) and the amber family count as brand colours; greys, whites, greens and anything inside url(...) or a
// comment are left alone. Run it again after adding new colours to the stylesheets: it skips what is already a variable, then rewrites
// src/lib/theme-colors.ts (the list the server uses to work out each variable's value for a chosen theme).
//
//   node tools/theme-tokens.mjs           tokenise new colours and refresh the list
//   node tools/theme-tokens.mjs --check   only report colours that are not variables yet (exit 1 if there are any)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const check = process.argv.includes("--check");

function hsl(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, d = mx - mn;
  if (!d) return { h: 0, s: 0, l };
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = mx === r ? ((g - b) / d + (g < b ? 6 : 0)) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return { h: h * 60, s, l };
}
/** "p" for the navy/blue family, "a" for the amber family, "" for everything else (kept as is). */
function family(hex) {
  const { h, s, l } = hsl(hex);
  if (s >= 0.18 && h >= 195 && h <= 250) return "p";
  if (s >= 0.4 && l >= 0.18 && h >= 25 && h <= 55) return "a";
  return "";
}
const toHex = (r, g, b) => "#" + [r, g, b].map((n) => Math.min(255, +n).toString(16).padStart(2, "0")).join("");

const SKIP = /(\/\*[\s\S]*?\*\/|url\((?:"[^"]*"|'[^']*'|[^)]*)\)|var\(--z[cr]-[0-9a-f]{6},[^)]*\))/gi;
const HEX = /#[0-9a-fA-F]{6}\b/g;
const RGB = /(rgba?\()\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})(\s*[,)])/g;

const hexUsed = new Map(), rgbUsed = new Map();
let pending = 0;

function convert(css) {
  return css.split(SKIP).map((part, i) => {
    if (i % 2) return part; // a comment, url(...) or an existing variable
    return part
      .replace(HEX, (m) => {
        const hex = m.toLowerCase();
        const f = family(hex);
        if (!f) return m;
        pending++;
        return check ? m : `var(--zc-${hex.slice(1)},${hex})`;
      })
      .replace(RGB, (m, fn, r, g, b, tail) => {
        if ([r, g, b].some((n) => +n > 255)) return m;
        const hex = toHex(r, g, b);
        if (!family(hex)) return m;
        pending++;
        return check ? m : `${fn}var(--zr-${hex.slice(1)},${+r},${+g},${+b})${tail}`;
      });
  }).join("");
}

const files = readdirSync(pub).filter((f) => /^zk-.*\.css$/.test(f)).sort();
// inline colours in the section markup (SVG gradient stops, the product cards) are written as variables by hand; the list needs them too
const extra = readFileSync(join(root, "src/lib/sections.ts"), "utf8");
for (const m of extra.matchAll(/var\(--zc-([0-9a-f]{6}),#([0-9a-f]{6})\)/gi)) hexUsed.set("#" + m[1].toLowerCase(), family("#" + m[1].toLowerCase()));
for (const f of files) {
  const path = join(pub, f);
  const before = readFileSync(path, "utf8");
  const after = convert(before);
  if (!check && after !== before) writeFileSync(path, after);
  // collect every variable now present (new and old)
  for (const m of (check ? before : after).matchAll(/var\(--zc-([0-9a-f]{6}),#([0-9a-f]{6})\)/gi)) hexUsed.set("#" + m[1].toLowerCase(), family("#" + m[1].toLowerCase()));
  for (const m of (check ? before : after).matchAll(/var\(--zr-([0-9a-f]{6}),/gi)) rgbUsed.set("#" + m[1].toLowerCase(), family("#" + m[1].toLowerCase()));
  if (!check && after !== before) console.log("tokenised", f);
}

if (check) {
  console.log(pending ? `${pending} brand colour(s) are not variables yet. Run: node tools/theme-tokens.mjs` : "All brand colours are variables.");
  process.exit(pending ? 1 : 0);
}

const list = (m) => [...m.entries()].sort((a, b) => hsl(a[0]).l - hsl(b[0]).l).map(([hex, f]) => `["${hex.slice(1)}", "${f}"]`).join(", ");
writeFileSync(join(root, "src/lib/theme-colors.ts"),
`// GENERATED by tools/theme-tokens.mjs from public/zk-*.css. Do not edit by hand.
// Every brand colour the stylesheets use as a variable: [hex without #, family]. "p" is the navy/blue family, "a" the amber family.
// THEME_HEX are the --zc-<hex> variables (a colour); THEME_RGB are the --zr-<hex> variables ("r,g,b", used inside rgba()).
export type Family = "p" | "a";
export const THEME_HEX: [string, Family][] = [${list(hexUsed)}];
export const THEME_RGB: [string, Family][] = [${list(rgbUsed)}];
`);
console.log(`theme-colors.ts: ${hexUsed.size} colours, ${rgbUsed.size} rgb triples`);
